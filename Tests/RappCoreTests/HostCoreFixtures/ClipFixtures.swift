    func testPasteSession() {
        var cases: [[String: Any]] = []
        func trace(_ name: String, _ steps: [(String, Double)]) {
            var p = PasteSession()
            var ins: [[String: Any]] = []
            var outs: [Any] = []
            for (op, now) in steps {
                switch op {
                case "started": ins.append(["op": op, "now": now]); outs.append(p.pasteStarted(now: now))
                case "finished": ins.append(["op": op, "now": now]); p.pasteFinished(now: now); outs.append(NSNull())
                case "due": ins.append(["op": op, "now": now]); outs.append(p.restoreDue(now: now))
                default: ins.append(["op": "restored"]); p.restored(); outs.append(NSNull())
                }
            }
            cases.append(Self.c(name, ["fn": "trace", "steps": ins], outs))
        }
        trace("saves once, restores 2 s after the last", [
            ("started", 0), ("finished", 0.2), ("started", 1.0), ("finished", 1.2), ("due", 3.1), ("due", 3.25),
            ("restored", 0), ("due", 9), ("started", 10),
        ])
        trace("not due while a paste is in flight", [
            ("started", 0), ("started", 0.1), ("finished", 0.2), ("due", 5), ("finished", 5.5), ("due", 7.4), ("due", 7.5),
        ])
        trace("exactly two seconds is due", [("started", 0), ("finished", 1), ("due", 3)])
        trace("finish without start is floored", [("finished", 1), ("due", 9), ("started", 9), ("finished", 9), ("due", 11)])
        trace("nothing saved is never due", [("due", 0), ("due", 100)])
        trace("restored while in flight forgets it", [("started", 0), ("restored", 0), ("started", 1), ("finished", 1), ("due", 3)])
        F.check("paste-session.json", F.cases(cases))
    }

