    // MARK: - transfer-chunks.bin

    /// Records:
    /// - tag 0: `u64 seed, u64 size, sized(first 64 bytes), sized(last 64 bytes)` of the source;
    /// - tag 1 / tag 2: one per chunk fetched from offset 0 / 300 000: `u64 position, u32 length`
    ///   (the bytes are the source's at that position, which Rust checks);
    /// - tag 3: one per 256 KiB chunk written through `PutSink`: `u64 have after it,
    ///   u8 done, u64 part size on disk (u64.max once the part is gone), sized(part name)`;
    /// - tag 4: the final file: `sized(name), u64 size`.
    func testTransferChunks() throws {
        let seed: UInt64 = 700
        let size = 700 * 1024
        var rng = HostRNG(seed: seed)
        let data = rng.bytes(size)
        let t = try TransferTrace(limit: 256 << 20)
        defer { t.cleanUp() }
        try Data(data).write(to: t.dir.appendingPathComponent("big.bin"))
        let attrs = try FileManager.default.attributesOfItem(atPath: t.dir.appendingPathComponent("big.bin").path)
        let ref = FileRef(url: t.dir.appendingPathComponent("big.bin"), size: UInt64(size),
                          modified: attrs[.modificationDate] as! Date)
        let clip = t.store.clips.add(.files([ClipFile(name: "big.bin", bytes: UInt64(size))]), payload: .files([ref]))

        var items: [(tag: UInt8, payload: [UInt8])] = []
        items.append((0, F.u64(seed) + F.u64(UInt64(size)) + F.sized(Array(data.prefix(64))) + F.sized(Array(data.suffix(64)))))
        for (tag, start) in [(UInt8(1), UInt64(0)), (UInt8(2), UInt64(300_000))] {
            let source = try t.store.fetch(clip: clip.id, file: 0, offset: start)
            var position = start
            while let chunk = try source.next() {
                XCTAssertEqual(chunk, Array(data[Int(position)..<Int(position) + chunk.count]))
                items.append((tag, F.u64(position) + F.u32(UInt32(chunk.count))))
                position += UInt64(chunk.count)
            }
        }
        let sink = try t.store.put(item: 1, kind: .files, uti: "", name: "big.bin", total: UInt64(size))
        var at = 0
        while at < size {
            let end = min(at + chunkSize, size)
            let done = try sink.write(Array(data[at..<end]))
            at = end
            let parts = ((try? FileManager.default.contentsOfDirectory(atPath: t.uploads.path)) ?? [])
                .filter { $0.hasSuffix(".rapp-part") }.sorted()
            let partName = parts.first ?? ""
            let partSize: UInt64 = parts.isEmpty ? UInt64.max
                : ((try? FileManager.default.attributesOfItem(atPath: t.uploads.appendingPathComponent(partName).path))?[.size]
                    as? NSNumber)?.uint64Value ?? UInt64.max
            items.append((3, F.u64(sink.have) + [done ? 1 : 0] + F.u64(partSize) + F.sized(Array(partName.utf8))))
        }
        guard case let .file(url)? = t.store.received(1) else { return XCTFail("not received") }
        let finalSize = ((try? FileManager.default.attributesOfItem(atPath: url.path))?[.size] as? NSNumber)?.uint64Value ?? 0
        items.append((4, F.sized(Array(url.lastPathComponent.utf8)) + F.u64(finalSize)))
        F.check("transfer-chunks.bin", F.records(items))
    }
}

/// Steps on one `ClipStore`.
fileprivate final class ClipTrace {
    let store: ClipStore
    var steps: [[String: Any]] = []
    var outs: [Any] = []
    init(_ store: ClipStore) { self.store = store }

    func changed(_ cc: Int, _ front: Bool) {
        steps.append(["op": "changed", "cc": cc, "front": front])
        outs.append(store.changed(changeCount: cc, targetFrontmost: front))
    }
    func own(_ cc: Int) {
        steps.append(["op": "own", "cc": cc]); store.noteOwnWrite(changeCount: cc); outs.append(NSNull())
    }
    func add(_ info: ClipInfo) {
        steps.append(["op": "add", "info": ClipFixtures.info(info)])
        outs.append(Int(store.add(info, payload: .inline).id))
    }
    func clip(_ id: UInt32) {
        steps.append(["op": "clip", "id": Int(id)])
        outs.append(store.clip(id).map { ClipFixtures.info($0.info) } ?? NSNull())
    }
}

