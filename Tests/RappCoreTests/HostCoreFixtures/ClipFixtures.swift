/// Clipboard rules and transfers for `rust/host-core/tests/rules_clip.rs` and
/// `rust/host-core/tests/transfers.rs`.
///
/// - `clip-rules.json`: pure functions, `in.fn` names one:
///   `clip_kind {types}` (out `{"kind", "uti"}`), `concealed {types}` (bool),
///   `should_restore {last, current}` (bool), `resume_offset {part, total}` (number),
///   `safe_file_name {raw}` (string), `unique_name {name, existing}` (string),
///   `clip_text {fill, count, tail}` — the text is `fill` repeated `count` times then `tail`,
///   so a 1 MiB input stays out of the file (out `{"len", "truncated", "end"}`: UTF-8 length,
///   the flag, hex of the last 16 bytes kept), and `constants` (out: the Swift constants).
/// - `paste-session.json`: traces on one `PasteSession`: `started {now}` (bool),
///   `finished {now}`, `due {now}` (bool), `restored`.
/// - `clip-store.json`: two kinds of trace.
///   `fn == "clips"`: one `ClipStore(changeCount: in.change)`; steps `changed {cc, front}`
///   (bool), `own {cc}`, `add {info}` (out: id), `clip {id}` (out: info or null).
///   `fn == "slots"`: one `SideSlots(limit: in.limit)`; steps `take` (bool), `release`.
///   `fn == "transfers"`: a `TransferStore` in a fresh temporary folder, see `TransferTrace`.
/// - `transfer-chunks.bin`: a 700 KiB seeded file, see `testTransferChunks`.
///
/// `info` is `{"type": "text", "text", "truncated"}`, `{"type": "image", "width", "height",
/// "bytes"}`, `{"type": "files", "files": [{"name", "bytes"}]}`, `{"type": "data", "uti",
/// "bytes"}` or `{"type": "unsupported", "text"}`. A transfer event is `{"dir", "kind" (raw
/// value), "bytes", "name"}`.
///
/// Covers every host-side scenario of ClipboardTests and TransferTests, plus text of exactly
/// 1 MiB and of 1 MiB + 1 byte ending inside a 4-byte character, a cut between a letter and
/// its combining mark, a put whose total is smaller than the part already written (starts
/// over from 0), and 0-byte puts. The 100/101-file limit lives in `rapp-host`'s
/// `ClipboardWatcher`, which a fixture cannot call; Rust checks the constant only.
final class ClipFixtures: XCTestCase {
    private typealias F = HostFixture

    private static func c(_ name: String, _ input: [String: Any], _ out: Any) -> [String: Any] {
        ["name": name, "in": input, "out": out]
    }

    static func info(_ i: ClipInfo) -> [String: Any] {
        switch i {
        case let .text(t, truncated): return ["type": "text", "text": t, "truncated": truncated]
        case let .image(w, h, b): return ["type": "image", "width": Int(w), "height": Int(h), "bytes": b]
        case let .files(files):
            return ["type": "files", "files": files.map { ["name": $0.name, "bytes": $0.bytes] as [String: Any] }]
        case let .data(uti, b): return ["type": "data", "uti": uti, "bytes": b]
        case let .unsupported(t): return ["type": "unsupported", "text": t]
        }
    }

    static func event(_ e: WorkerEvent) -> Any {
        guard case let .transfer(dir, kind, bytes, name) = e else { return NSNull() }
        return ["dir": dir.rawValue, "kind": Int(kind.rawValue), "bytes": bytes, "name": F.opt(name)] as [String: Any]
    }

