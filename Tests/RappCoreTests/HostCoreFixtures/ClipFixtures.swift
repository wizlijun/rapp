///
/// Steps: `source {name, size, seed}` writes `HostRNG(seed).bytes(size)`; `append {name, hex}`;
/// `remove {name}`; `file_clip {sources, names}` (out: id; each `FileRef` takes the file's
/// size and modification date now); `bytes_clip {info, size, seed}` (out: id); `text_clip
/// {text}` (out: id); `fetch {clip, file, offset}` (out `{"error"}` or `{"total", "transfer",
/// "chunks": [lengths], "position": first byte's offset}` — the bytes are the source's from
/// there on, which both sides check); `data {size, seed}` sets the buffer `write` slices;
/// `put {item, kind, uti, name, total}` (out `{"error"}` or `{"have", "transfer"}`);
/// `write {item, from, to}` and `write_hex {item, hex}` go to the sink the last successful
/// `put` of that item returned (out `{"error"}` or `{"done", "have"}`); `received {item}`
/// (out: null, `{"text"}`, `{"image": hex}`, `{"data": hex, "uti"}` or `{"file": name}`,
/// the name inside the uploads folder); `preexisting {name, text}` writes a file into the
/// uploads folder; `listing` (out: the uploads folder's names, sorted; `[]` if missing).
fileprivate final class TransferTrace {
    let dir: URL
    var uploads: URL { dir.appendingPathComponent("uploads") }
    let store: TransferStore
    var steps: [[String: Any]] = []
    var outs: [Any] = []
    private var sinks: [UInt32: PutSink] = [:]
    private var sources: [String: [UInt8]] = [:]
    private var buffer: [UInt8] = []
    /// What each clip id hands out, to check fetched bytes here too.
    private var clipBytes: [UInt32: [[UInt8]]] = [:]

    init(limit: Int) throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("rapp-clip-fixture-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        dir = root
        store = TransferStore(clips: ClipStore(changeCount: 0), uploads: root.appendingPathComponent("uploads"), memoryLimit: limit)
    }
    func cleanUp() { try? FileManager.default.removeItem(at: dir) }

    private func record(_ step: [String: Any], _ out: Any) { steps.append(step); outs.append(out) }

    func source(_ name: String, size: Int, seed: UInt64) {
        var rng = HostRNG(seed: seed)
        let bytes = rng.bytes(size)
        try! Data(bytes).write(to: dir.appendingPathComponent(name))
        sources[name] = bytes
        record(["op": "source", "name": name, "size": size, "seed": seed], NSNull())
    }
    func append(_ name: String, _ bytes: [UInt8]) {
        let h = try! FileHandle(forWritingTo: dir.appendingPathComponent(name))
        try! h.seekToEnd(); try! h.write(contentsOf: Data(bytes)); try! h.close()
        sources[name, default: []] += bytes
        record(["op": "append", "name": name, "hex": F.hex(bytes)], NSNull())
    }
    func remove(_ name: String) {
        try! FileManager.default.removeItem(at: dir.appendingPathComponent(name))
        record(["op": "remove", "name": name], NSNull())
    }
    private typealias F = HostFixture

    @discardableResult
    func fileClip(_ names: [String], names shown: [String]) -> UInt32 {
        var refs: [FileRef] = []
        for n in names {
            let url = dir.appendingPathComponent(n)
            let a = try! FileManager.default.attributesOfItem(atPath: url.path)
            refs.append(FileRef(url: url, size: (a[.size] as! NSNumber).uint64Value, modified: a[.modificationDate] as! Date))
        }
        let files = shown.enumerated().map { ClipFile(name: $0.element, bytes: refs[min($0.offset, refs.count - 1)].size) }
        let c = store.clips.add(.files(files), payload: .files(refs))
        clipBytes[c.id] = names.map { sources[$0] ?? [] }
        record(["op": "file_clip", "sources": names, "names": shown], Int(c.id))
        return c.id
    }
    @discardableResult
    func bytesClip(_ info: ClipInfo, size: Int, seed: UInt64) -> UInt32 {
        var rng = HostRNG(seed: seed)
        let bytes = rng.bytes(size)
        let c = store.clips.add(info, payload: .bytes(bytes))
        clipBytes[c.id] = [bytes]
        record(["op": "bytes_clip", "info": ClipFixtures.info(info), "size": size, "seed": seed], Int(c.id))
        return c.id
    }
    @discardableResult
    func textClip(_ text: String) -> UInt32 {
        let c = store.clips.add(.text(text, truncated: false), payload: .inline)
        record(["op": "text_clip", "text": text], Int(c.id))
        return c.id
    }
    func fetch(_ clip: UInt32, _ file: UInt16, _ offset: UInt64) {
        let step: [String: Any] = ["op": "fetch", "clip": Int(clip), "file": Int(file), "offset": offset]
        do {
            let source = try store.fetch(clip: clip, file: file, offset: offset)
            var lengths: [Int] = []
            var got: [UInt8] = []
            while let chunk = try source.next() { lengths.append(chunk.count); got += chunk }
            if let all = clipBytes[clip], Int(file) < all.count {
                XCTAssertEqual(got, Array(all[Int(file)][Int(offset)...]))
            }
            record(step, ["total": source.total, "transfer": ClipFixtures.event(source.transfer), "chunks": lengths,
                          "position": offset] as [String: Any])
        } catch let e as TransferError {
            record(step, ["error": e.reason])
        } catch {
            record(step, ["error": "file changed"])
        }
    }
    func data(size: Int, seed: UInt64) {
        var rng = HostRNG(seed: seed)
        buffer = rng.bytes(size)
        record(["op": "data", "size": size, "seed": seed], NSNull())
    }
    private func kindName(_ k: ClipKind) -> Int { Int(k.rawValue) }
    func put(_ item: UInt32, _ kind: ClipKind, _ uti: String, _ name: String, _ total: UInt64) {
        let step: [String: Any] = ["op": "put", "item": Int(item), "kind": kindName(kind), "uti": uti, "name": name, "total": total]
        do {
            let sink = try store.put(item: item, kind: kind, uti: uti, name: name, total: total)
            sinks[item] = sink
            record(step, ["have": sink.have, "transfer": ClipFixtures.event(sink.transfer)] as [String: Any])
        } catch let e as TransferError {
            record(step, ["error": e.reason])
        } catch {
            record(step, ["error": "\(error)"])
        }
    }
    private func write(_ step: [String: Any], _ item: UInt32, _ bytes: [UInt8]) {
        guard let sink = sinks[item] else { return record(step, ["error": "no sink"]) }
        do {
            let done = try sink.write(bytes)
            record(step, ["done": done, "have": sink.have] as [String: Any])
        } catch let e as TransferError {
            record(step, ["error": e.reason])
        } catch {
            record(step, ["error": "\(error)"])
        }
    }
    func write(_ item: UInt32, _ from: Int, _ to: Int) {
        write(["op": "write", "item": Int(item), "from": from, "to": to], item, Array(buffer[from..<to]))
    }
    func writeHex(_ item: UInt32, _ bytes: [UInt8]) {
        write(["op": "write_hex", "item": Int(item), "hex": F.hex(bytes)], item, bytes)
    }
    func received(_ item: UInt32) {
        let step: [String: Any] = ["op": "received", "item": Int(item)]
        switch store.received(item) {
        case nil: record(step, NSNull())
        case let .text(s)?: record(step, ["text": s])
        case let .image(b)?: record(step, ["image": F.hex(b)])
        case let .data(uti, b)?: record(step, ["data": F.hex(b), "uti": uti])
        case let .file(url)?:
            XCTAssertEqual(url.deletingLastPathComponent().standardizedFileURL.path, uploads.standardizedFileURL.path)
            record(step, ["file": url.lastPathComponent])
        }
    }
    func preexisting(_ name: String, _ text: String) {
        try! FileManager.default.createDirectory(at: uploads, withIntermediateDirectories: true)
        try! Data(text.utf8).write(to: uploads.appendingPathComponent(name))
        record(["op": "preexisting", "name": name, "text": text], NSNull())
    }
    func listing() {
        let names = ((try? FileManager.default.contentsOfDirectory(atPath: uploads.path)) ?? []).sorted()
        record(["op": "listing"], names)
    }
}
