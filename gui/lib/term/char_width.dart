bool _inTable(List<(int, int)> table, int rune) {
  var lo = 0, hi = table.length - 1;
  while (lo <= hi) {
    final mid = (lo + hi) >> 1;
    final (a, b) = table[mid];
    if (rune < a) {
      hi = mid - 1;
    } else if (rune > b) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

int cellWidth(int rune) {
  if (rune < 0x300) return 1;
  if (_inTable(_zero, rune)) return 0;
  if (_inTable(_wide, rune)) return 2;
  return 1;
}
