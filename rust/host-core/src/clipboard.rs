//! The host-side clipboard rules, ported from `Sources/RappCore/Clipboard.swift`. The UTI
//! strings are Swift's and stay the wire values; the Windows platform maps its own clipboard
//! formats onto them. The client-only helpers (`pasteDecision`, `composerItems`, `formatSize`,
//! …) are not ported: no host path uses them.

// `maxClipText`, `maxClipFiles`, `inlinePasteLimit`, `chunkSize`, `maxSideConnections`
// (Clipboard.swift:24-29). The protocol module owns them; one value, two paths.
pub use crate::protocol::{CHUNK_SIZE, INLINE_PASTE_LIMIT, MAX_CLIP_FILES, MAX_CLIP_TEXT, MAX_SIDE_CONNECTIONS};
/// Spec §6.7: an image is kept as PNG under 64 MiB, other data under 64 MiB too
/// (`ClipboardWatcher.memoryLimit`, compared with `<`).
pub const MAX_CLIP_IMAGE: usize = 64 << 20;
/// Same limit for other data (`ClipboardWatcher.memoryLimit`).
pub const MAX_CLIP_DATA: usize = 64 << 20;

pub const TYPE_FILE_URL: &str = "public.file-url";
pub const TYPE_PNG: &str = "public.png";
pub const TYPE_TIFF: &str = "public.tiff";
pub const TYPE_UTF8_TEXT: &str = "public.utf8-plain-text";

/// Seconds to wait before re-trying a failed side-connection transfer (`retryDelays`).
pub const RETRY_DELAYS: [f64; 3] = [1.0, 2.0, 4.0];

/// The texts `ClipboardWatcher` announces for clips it will not carry.
pub const TOO_MANY_FILES: &str = "文件太多（不支持）";
pub const FOLDER_UNSUPPORTED: &str = "文件夹（不支持）";

/// What a clipboard holds, by priority (`ClipSource`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipSource {
    Files,
    Image,
    Text,
    Data { uti: String },
    None,
}

/// Picks what a clipboard holds by priority: files, image, text, then the first other type
/// (`clipKind(types:)`).
pub fn clip_kind(types: &[String]) -> ClipSource {
    let has = |t: &str| types.iter().any(|x| x == t);
    if has(TYPE_FILE_URL) {
        return ClipSource::Files;
    }
    if has(TYPE_PNG) || has(TYPE_TIFF) {
        return ClipSource::Image;
    }
    if has(TYPE_UTF8_TEXT) {
        return ClipSource::Text;
    }
    if let Some(first) = types.first() {
        return ClipSource::Data { uti: first.clone() };
    }
    ClipSource::None
}

/// Cuts text to `MAX_CLIP_TEXT` UTF-8 bytes, backing up to a scalar boundary (`clipText`).
/// A Rust `char` boundary is a Unicode scalar boundary, which is what Swift checks with
/// `samePosition(in: unicodeScalars)`.
pub fn clip_text(s: &str) -> (String, bool) {
    if s.len() <= MAX_CLIP_TEXT {
        return (s.to_string(), false);
    }
    let mut idx = MAX_CLIP_TEXT;
    while idx > 0 && !s.is_char_boundary(idx) {
        idx -= 1;
    }
    (s[..idx].to_string(), true)
}

/// Types that mark a copy as secret or machine-made (nspasteboard.org); never recorded
/// (`isConcealedClip`). Which Windows clipboard formats the platform maps onto these is
/// probe P's question (spec §6.7), not decided here.
pub fn is_concealed_clip(types: &[String]) -> bool {
    const MARKS: [&str; 3] =
        ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
    types.iter().any(|t| MARKS.contains(&t.as_str()))
}

/// A restore may only overwrite the clipboard if nothing but us wrote to it since our last
/// write (`shouldRestore`).
pub fn should_restore(last_own_change: i64, current: i64) -> bool {
    current <= last_own_change
}

/// Where to resume an upload whose part file holds `part_size` bytes (`resumeOffset`).
pub fn resume_offset(part_size: u64, total: u64) -> u64 {
    if part_size > total {
        0
    } else {
        part_size
    }
}

/// Keeps only the last `/` component, without `:` or leading dots; falls back to `file`
/// (`safeFileName`). Windows applies `filename::portable_file_name` after this.
pub fn safe_file_name(raw: &str) -> String {
    let last = raw.split('/').rfind(|p| !p.is_empty()).unwrap_or("");
    let mut name = last.replace(':', "");
    while name.starts_with('.') {
        // Swift's `removeFirst()` drops one Character; a lone "." is one scalar.
        name.remove(0);
    }
    if name.is_empty() {
        "file".to_string()
    } else {
        name
    }
}

/// One burst of pastes on A: save the clipboard once, restore 2 s after the last paste
/// (`PasteSession`).
#[derive(Debug, Clone, Default)]
pub struct PasteSession {
    saved: bool,
    in_flight: i64,
    last_finish: f64,
}

impl PasteSession {
    pub const RESTORE_DELAY: f64 = 2.0;

    pub fn new() -> Self {
        Self::default()
    }

    /// True when the caller must save the clipboard first.
    pub fn paste_started(&mut self, _now: f64) -> bool {
        self.in_flight += 1;
        if self.saved {
            return false;
        }
        self.saved = true;
        true
    }

    pub fn paste_finished(&mut self, now: f64) {
        self.in_flight = (self.in_flight - 1).max(0);
        self.last_finish = now;
    }

    pub fn restore_due(&self, now: f64) -> bool {
        self.saved && self.in_flight == 0 && now - self.last_finish >= Self::RESTORE_DELAY
    }

    pub fn restored(&mut self) {
        self.saved = false;
        self.in_flight = 0;
    }
}
